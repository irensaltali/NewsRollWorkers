CREATE OR REPLACE FUNCTION public.get_image_prompt_optimizer_stats(p_days INTEGER DEFAULT 30)
RETURNS TABLE (
  optimizer_config_id BIGINT,
  optimizer_key TEXT,
  optimizer_version TEXT,
  total_generated BIGINT,
  succeeded BIGINT,
  failed BIGINT,
  total_engagements BIGINT,
  total_impressions BIGINT,
  engagement_rate DOUBLE PRECISION
)
LANGUAGE SQL
AS $$
  WITH base AS (
    SELECT
      optimizer_config_id,
      optimizer_key,
      optimizer_version,
      story_id,
      status
    FROM public.image_prompt_generations
    WHERE source = 'media_pipeline'
      AND created_at > now() - make_interval(days => GREATEST(COALESCE(p_days, 30), 1))
  )
  SELECT
    base.optimizer_config_id,
    base.optimizer_key,
    base.optimizer_version,
    COUNT(*)::BIGINT AS total_generated,
    COUNT(*) FILTER (WHERE base.status = 'ready')::BIGINT AS succeeded,
    COUNT(*) FILTER (WHERE base.status <> 'ready')::BIGINT AS failed,
    COALESCE(SUM(pfe.engagement_count), 0)::BIGINT AS total_engagements,
    COALESCE(SUM(pfe.impression_count), 0)::BIGINT AS total_impressions,
    CASE
      WHEN COALESCE(SUM(pfe.impression_count), 0) = 0 THEN 0
      ELSE COALESCE(SUM(pfe.engagement_count), 0)::DOUBLE PRECISION / NULLIF(SUM(pfe.impression_count), 0)
    END AS engagement_rate
  FROM base
  LEFT JOIN public.published_feed_entries pfe
    ON pfe.story_id = base.story_id
  GROUP BY
    base.optimizer_config_id,
    base.optimizer_key,
    base.optimizer_version
  ORDER BY total_generated DESC, optimizer_key ASC, optimizer_version ASC;
$$;
