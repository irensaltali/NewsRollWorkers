CREATE TABLE IF NOT EXISTS public.image_prompt_optimizer_configs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT NOT NULL,
  version TEXT NOT NULL,
  name TEXT NOT NULL,
  provider TEXT NOT NULL DEFAULT 'openai',
  model TEXT NOT NULL,
  max_completion_tokens INTEGER NOT NULL DEFAULT 500,
  system_prompt TEXT NOT NULL,
  user_prompt_template TEXT NOT NULL,
  settings JSONB NOT NULL DEFAULT '{}'::jsonb,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS image_prompt_optimizer_configs_key_version_idx
  ON public.image_prompt_optimizer_configs (key, version);

DROP INDEX IF EXISTS public.image_prompt_optimizer_configs_active_key_idx;
CREATE UNIQUE INDEX image_prompt_optimizer_configs_active_key_idx
  ON public.image_prompt_optimizer_configs (key)
  WHERE active = true;

CREATE TABLE IF NOT EXISTS public.image_prompt_generations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  story_id BIGINT,
  source TEXT NOT NULL,
  optimizer_config_id BIGINT,
  optimizer_key TEXT NOT NULL,
  optimizer_version TEXT NOT NULL,
  optimizer_provider TEXT NOT NULL,
  optimizer_model TEXT NOT NULL,
  optimizer_input JSONB NOT NULL DEFAULT '{}'::jsonb,
  optimized_prompt TEXT,
  status TEXT NOT NULL,
  latency_ms INTEGER,
  error_text TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS image_prompt_generations_story_created_idx
  ON public.image_prompt_generations (story_id, created_at DESC);

CREATE INDEX IF NOT EXISTS image_prompt_generations_optimizer_created_idx
  ON public.image_prompt_generations (optimizer_config_id, created_at DESC);

ALTER TABLE public.story_media
